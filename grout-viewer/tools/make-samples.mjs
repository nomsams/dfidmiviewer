// Embeds example .DFI files as base64 so the app also works when opened straight from disk.
import fs from 'node:fs';
const files = process.argv.slice(2);
let out = '/* Generated by tools/make-samples.mjs - example measurement files */\nwindow.GV_SAMPLES = [\n';
for (const f of files) out += `  { name: ${JSON.stringify(f.split(/[\/]/).pop())}, b64: "${fs.readFileSync(f).toString('base64')}" },\n`;
out += '];\n';
fs.writeFileSync(new URL('../js/samples.js', import.meta.url), out);
console.log('wrote', files.length, 'samples');
